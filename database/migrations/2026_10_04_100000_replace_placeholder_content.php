    /** The design kit's sample partner logos are not real partners. */
    protected function removeSamplePartners(): void
    {
        $samples = DB::table('media')
            ->where('disk', 'public')
            ->where('path', 'like', 'media/designed/about-partner-%')
            ->pluck('path', 'id');

        if ($samples->isEmpty()) {
            return;
        }

        $setting = DB::table('settings')->where('group', 'about')->where('key', 'partner_media_ids');
        $current = preg_split('/[\s,،]+/u', (string) $setting->value('value'), -1, PREG_SPLIT_NO_EMPTY);
        $kept = array_values(array_diff($current, array_map('strval', $samples->keys()->all())));

        $setting->update(['value' => $kept ? implode(',', $kept) : null]);

        DB::table('media')->whereIn('id', $samples->keys())->delete();
        Storage::disk('public')->delete($samples->values()->all());
    }
